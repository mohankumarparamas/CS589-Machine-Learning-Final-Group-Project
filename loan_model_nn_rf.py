def predict(node, row):
  # If it is not a dictionary, it is a leaf (0 or 1)
  if not isinstance(node, dict):
    return node

  attribute = node['attribute']
  # If the attribute is numeric, we use the saved stats to decide the branch
  if 'stats' in node:
    stats = node['stats']
    x = row[attribute]
    # Using the same logic as in `build_tree` to decide which class 'x' belongs to
    probs = {}
    for c, info in stats.items():
      exponent = np.exp(-((x - info['mu'])**2 / (2 * info['sigma']**2)))
      f_X = (1 / (np.sqrt(2 * np.pi) * info['sigma'])) * exponent
      probs[c] = info['prior'] * f_X
    # The winning class tells us which key to look for in 'children'
    best_c = max(probs, key=probs.get)
    return predict(node['children'][str(best_c)], row)
  # If it is categorical, the value is the direct key
  else:
    value = row[attribute]
    if value in node['children']:
      return predict(node['children'][value], row)
    else:
      # If the value does not exist, position at the first available branch
      return predict(list(node['children'].values())[0], row)


