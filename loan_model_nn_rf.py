# Entropy of the original dataset classes: unacceptable, acceptable, good, and very good.

def entropy(data):
  categories_probs = data.value_counts(normalize=True)
  log_categories_probs = np.log2(categories_probs)
  I_prob = -np.sum(categories_probs * log_categories_probs)
  return I_prob

# Calculates the weighted entropy of a dataset split by a specific attribute.
# Handles categorical (_cat) and numerical (_num) data differently.

def average_entropy(dataset, attribute_test_m):

  if len(dataset) == 0:
    return 0
  total_samples = len(dataset)
  entropy_total_sum = 0

  # Case categorical data
  if attribute_test_m.endswith('_cat'):
    #partition_atrib = dataset_car.groupby('buying_price').groups.items()
    partition_atrib = dataset.groupby(attribute_test_m).groups.items()
    count_class = []
    entropy_average = 0
    for categories, index in partition_atrib:
      sub_dataset = dataset['label'].loc[index]
      entropy_value = entropy(sub_dataset)
      count_class = sub_dataset.value_counts().sum()
      weight = count_class / dataset.shape[0]
      entropy_average += entropy_value * weight

  # Case numerical data (Gaussian density is used)
  if attribute_test_m.endswith('_num'):
    classes = dataset['label'].unique()
    total_samples = len(dataset)
    # Calculating parameters (mu, sigma) and the Prior P(class) for EACH CLASS separately
    class_info = {}
    for c in classes:
      subset_c = dataset[dataset['label'] == c][attribute_test_m]
      mu = subset_c.mean()
      sigma = subset_c.std() + 1e-9 # if division by zero
      prior = len(subset_c) / total_samples
      class_info[c] = {'mu': mu, 'sigma': sigma, 'prior': prior}

    # Calculating the posteriori
    entropy_total_sum = 0
    for x in dataset[attribute_test_m]:
      posteriors = {}
      for c, info in class_info.items():
        exponent = np.exp(-((x - info['mu'])**2 / (2 * info['sigma']**2)))
        gauss_density = (1 / (np.sqrt(2 * np.pi) * info['sigma'])) * exponent
        posteriors[c] = info['prior'] * gauss_density

      # Normalization
      total_p_x = sum(posteriors.values())
      if total_p_x > 0:
        instance_entropy = 0
        for c in classes:
          p_c_given_x = posteriors[c] / total_p_x
          if p_c_given_x > 0:
            instance_entropy -= p_c_given_x * np.log2(p_c_given_x)
            # Accumulating the entropy of this specific row.
        entropy_total_sum += instance_entropy

      else:
        entropy_total_sum += entropy(dataset['label'])
        # The final average is the sum of the individual uncertainties divided by N.
    entropy_average = entropy_total_sum / total_samples

  return entropy_average

def inf_Gain(entropy_each_attributes, entropy_class):
  max_gain = -1
  best_attribute = ''
  for key, value in entropy_each_attributes.items():
    inf_gain = entropy_class - value
    #print(f'The information gain for {key} is {inf_gain}')
    if inf_gain > max_gain:
            max_gain = inf_gain
            best_attribute = key
  return best_attribute, max_gain

