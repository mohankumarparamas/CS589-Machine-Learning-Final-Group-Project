def build_tree(dataset, L_attributes, current_depth=0, max_depth=5, min_samples_split=10, min_gain_criterion = 0.00001):

  # --------------------------- STOP CONDITIONS --------------------------------

  counts = dataset['label'].value_counts()
  majority_class = int(counts.idxmax())

  # Control 1. When it is a leaf node
  if len(counts) == 1 or len(L_attributes) == 0:
    return majority_class
  # ----------------------------------------------------------------------------
  # Control 2. When it is Maximum depth reached
  if current_depth >= max_depth:
    return majority_class
  # ----------------------------------------------------------------------------
  # Control 3. When there are minimal instances
  if len(dataset) < min_samples_split:
    return majority_class
  # ----------------------------------------------------------------------------


  # Calculating entropy in the subset
  I_class_subset = entropy(dataset['label'])
  #print(f"Entropía del subconjunto: {I_class_subset}")

  # Calculating average entropy of the remaining attributes
  entropy_remaining_attributes = {attr: average_entropy(dataset, attr) for attr in L_attributes}
  #print(f"Entropy of the remaining attributes:{entropy_remaining_attributes}")

  # Calculating the best attribute
  best_attribute, gain = inf_Gain(entropy_remaining_attributes, I_class_subset)
  #print(f"The best attribute: {best_attribute}")
  #print(f"Gain Information: {gain}")


  #  ------------ Control When we have minimal inf Gain  --------------
  if gain <= min_gain_criterion:
        # The majority decision of the current dataset
        leaf_class = dataset['label'].value_counts().idxmax()###
        #print(f"There is a leaf node due to zero gain {leaf_class}")
        return int(leaf_class)
  #  ---------------------------------------------------------------------------

  # Creting a new node
  node = {'attribute': best_attribute, 'children': {}}
  # Removing the leaf node found from L_attributes
  L_remaining = [col for col in L_attributes if col != best_attribute]

  # ----------------------------------------------------------------------------
  # We have 2 cases: 1. The best_attribute is categorical data (HW1) and
  # 2. The best_attribute is numerical data. Therefore, the division of nodes
  # depends on this.
  # ----------------------------------------------------------------------------

  # ----------------------------------------------------------------------------
  # Categorical data
  # ----------------------------------------------------------------------------

  if best_attribute.endswith('_cat'):

    for branch in dataset[best_attribute].unique():
      branch_mapping_to_class = dataset[dataset[best_attribute] == branch]['label']
      #counting how many times each class appears
      counts = branch_mapping_to_class.value_counts()  ###
      #print(f"branch: {branch}")
      #print(f"Class distribution:\n{counts}")
      # checking if there is only one class in the branch
      if len(counts) == 1:
            # It is leaf node
            leaf_class = counts.index[0].item() ###
            node['children'][branch] = leaf_class
            #print(f"Leaf node because only one class: {leaf_class}")
      elif not L_remaining:
            # If there are no more attributes, choosing the most frequent class (by majority).
                leaf_class = counts.idxmax().item() ###
                node['children'][branch] = leaf_class
                #print(f"Leaf node because there are no more attributes (L empty): {leaf_class}")
      else:
            #print('Continue dividing the data ...')
            #print(f"Testing of other attributes")
            subset_branch = dataset[dataset[best_attribute] == branch]
            # controlling the end of the dataset
            if len(subset_branch) < len(dataset):
              node['children'][branch] = build_tree(subset_branch, L_remaining)
              #print(f"The childre node in categorica data is {node}")
              #print("*"*50 + "Changing node division using numeric data")
            else:
              node['children'][branch] = counts.idxmax().item()
            #print("next stage --------" * 30)

  # ----------------------------------------------------------------------------
  # Numeric Case
  # ----------------------------------------------------------------------------
  else:
    stats = {}
    classes = dataset['label'].unique()
    for c in classes:
      subset_c = dataset[dataset['label'] == c][best_attribute]
      #class_key = int(c)
      stats[c] = {
          'mu': float(subset_c.mean()),
          'sigma': float(subset_c.std() + 1e-9),
          'prior': len(subset_c) / len(dataset)
      }
    # Creating the numerical nodo for the prediction function
    node['stats'] = stats

    # Calculating the class probability
    def class_probability(x):
      P_clase_X = {}
      for c, info in stats.items():
        exponent = np.exp(-((x - info['mu'])**2 / (2 * info['sigma']**2)))
        f_X = (1 / (np.sqrt(2 * np.pi) * info['sigma'])) * exponent
        P_clase_X[c] = info['prior'] * f_X
      return max(P_clase_X, key=P_clase_X.get)

    # Making the prediction based in the best attribute
    dataset_predictions = dataset[best_attribute].apply(class_probability)

    for c in classes:
      branch_key = str(c)
      subset_branch = dataset[dataset_predictions == c]
      if not subset_branch.empty and len(subset_branch) < len(dataset):
        node['children'][branch_key] = build_tree(subset_branch, L_remaining)
        #print(f"The childre node in numerical data is {node}")
      else:
        # It will be leaf
        node['children'][branch_key] = c

  return node

